// 那是**介绍 Laup 自己**的长文（61 块）。拿它当"新建文档"的开局，
// 等于每次写东西都得先删掉一整篇文档。
//
// ── 现在它只有一个空标题（2026-09-22 改）
//   上一版是 6 块占位稿纸（标题 / 正文 / 小标题 / 正文 / 引用 / 列表），
//   反馈是"预置太多"—— 打开先删一批占位文字，那是拿模板当负担。
//   现在的口径：**给纸，不给字**。只留一个空的一级标题，
//   点进去直接写标题，回车往下开新块（`\n` 编译出来就是下一块，实测过）。
//
// ⚠️ 为什么这里敢留**空**块（以前不敢，别照旧结论改回去）
//   实测发现过：`.laup-blk` 没有 min-height 时，空的 `<h1></h1>` 量出来高度是 **0px**，
//   几个 0 高度的块会叠在同一个 y 上，只有最上面那个点得中，而且盲测会**假通过**
//   （点中的其实是叠在那儿的别的元素）。
//   以前的解法是"每块都必须塞一个字"—— 那是绕开症状。
//   现在改在根上：`editor/index.html` 的 `.laup-blk` 有了 `min-height`，
//   空块照样占一行、点得中。所以骨架可以是空的。
//   ⚠️ 那条 min-height 不能删 —— 删了空块立刻变回 0px 且点不中。
//
